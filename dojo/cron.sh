#!/bin/sh
# Обновление находок DefectDojo по расписанию.
#
# Строка для cron — раз в два часа, в четверть чётного часа:
#
#   15 */2 * * * /srv/local-ai/dojo/cron.sh >> /var/log/local-ai-dojo.log 2>&1
#
# Ставится вместе с Confluence и Jira одной командой: ./install-cron.sh
#
# Четверть часа выбрана между Confluence (:00) и Jira (:30): все три индексации
# ходят в один эмбеддер, и одновременный старт давал бы тройную нагрузку на
# видеокарту, которую делит ещё и чат.
#
# Находки забираются по API целиком, а векторы пересчитываются только у
# изменившихся, поэтому прогон без изменений — это время одной выгрузки.
# Пропавшие из DefectDojo находки убираются из индекса; если пропало больше
# половины разом, индексатор ничего не удаляет и пишет предупреждение в лог.

set -eu

# У cron урезанный PATH, и docker может не найтись — тогда прогон молча
# ничего не делает. Дописываем обычные места прямо здесь, а не в crontab,
# чтобы не менять окружение чужих задач в том же расписании
PATH="/usr/local/bin:/usr/bin:/bin:${PATH:-}"
export PATH

cd "$(dirname "$0")/.."

LOCK=/tmp/local-ai-dojo.lock
exec 9>"$LOCK"
if ! flock -n 9; then
    echo "$(date '+%Y-%m-%d %H:%M:%S') прошлый прогон ещё идёт, пропускаю"
    exit 0
fi

echo "$(date '+%Y-%m-%d %H:%M:%S') выгрузка и индексация"
docker compose exec -T kb python -m kb.dojo_index

echo "$(date '+%Y-%m-%d %H:%M:%S') готово"
