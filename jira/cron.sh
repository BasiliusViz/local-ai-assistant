#!/bin/sh
# Обновление задач Jira по расписанию. Два режима:
#
#   jira/cron.sh           выгрузить изменившиеся задачи и проиндексировать
#   jira/cron.sh --prune   сверка: убрать задачи, вышедшие из охвата
#
# Строки для cron — обычный прогон раз в два часа, сверка раз в сутки ночью:
#
#   30 */2 * * * /srv/local-ai/jira/cron.sh >> /var/log/local-ai-jira.log 2>&1
#   15 3 * * *   /srv/local-ai/jira/cron.sh --prune >> /var/log/local-ai-jira.log 2>&1
#
# Сдвиг на полчаса от Confluence (он стартует в начале чётного часа) не
# случаен: обе индексации ходят в один эмбеддер, и одновременный старт давал бы
# двойную нагрузку на видеокарту, которую делит ещё и чат.
#
# Зачем отдельная сверка. Обычная выгрузка берёт только изменившееся и не
# замечает, что задача пропала: её удалили, перенесли, переназначили вне
# команды или она выпала из окна JIRA_SINCE. Сверка раз в сутки сравнивает
# номера задач в Jira с файлами на диске и убирает лишнее.
#
# Замок общий для обоих режимов: сверка не должна стартовать посреди обычной
# выгрузки, иначе может удалить файл, который выгрузка только что записала.

set -eu

# У cron урезанный PATH, и docker может не найтись — тогда прогон молча
# ничего не делает. Дописываем обычные места прямо здесь, а не в crontab,
# чтобы не менять окружение чужих задач в том же расписании
PATH="/usr/local/bin:/usr/bin:/bin:${PATH:-}"
export PATH

cd "$(dirname "$0")/.."

LOCK=/tmp/local-ai-jira.lock
exec 9>"$LOCK"
if ! flock -n 9; then
    echo "$(date '+%Y-%m-%d %H:%M:%S') прошлый прогон ещё идёт, пропускаю"
    exit 0
fi

if [ "${1:-}" = "--prune" ]; then
    echo "$(date '+%Y-%m-%d %H:%M:%S') сверка с Jira"
    docker compose exec -T kb python jira/sync.py --prune
else
    echo "$(date '+%Y-%m-%d %H:%M:%S') выгрузка"
    docker compose exec -T kb python jira/sync.py
fi

echo "$(date '+%Y-%m-%d %H:%M:%S') индексация"
docker compose exec -T kb python -m kb.jira_index /docs/jira

echo "$(date '+%Y-%m-%d %H:%M:%S') готово"
