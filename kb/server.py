"""MCP-сервер поиска по внутренней базе знаний.

Запуск (streamable-http, порт 8010):
    .venv\\Scripts\\python.exe -m kb.server

Только чтение: писать в базу может индексатор, но не модель. Иначе
ассистент начнёт «запоминать» собственные галлюцинации в корпоративную вики.
"""

import logging
import os
import sys

from mcp.server import MCPServer
from mcp.types import ToolAnnotations

from kb import code_retriever, config, dojo, dojo_retriever, jira_retriever
from kb.embedder import EmbedError
from kb.jira_retriever import JiraSearchError
from kb.retriever import SearchError, known_values, search

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    stream=sys.stderr,
)
log = logging.getLogger("kb")

HOST = os.getenv("KB_HOST", "0.0.0.0")
PORT = int(os.getenv("KB_PORT", "8010"))

mcp = MCPServer(
    "knowledge-base",
    instructions=(
        "Поиск по внутренним данным компании на русском языке: документация "
        "(kb_search), исходный код (code_search) и задачи Jira (jira_search). "
        "Инструменты вызываются только по явной просьбе, у каждого своё "
        "условие — оно описано в самом инструменте."
    ),
)


@mcp.tool(
    # readOnlyHint: инструмент только читает, ничего не меняет —
    # клиент может не спрашивать подтверждения на каждый вызов
    annotations=ToolAnnotations(readOnlyHint=True, openWorldHint=False),
)
def kb_search(
    query: str,
    top_k: int = config.DEFAULT_TOP_K,
    source_filter: str | None = None,
    space_filter: str | None = None,
    response_format: str = "concise",
) -> dict:
    """Ищет ответ во внутренней базе знаний компании.

    В базе лежит внутренняя документация на русском языке: регламенты выкатки
    сервисов, требования безопасности, инструкции по онбордингу, описания
    процессов. Это закрытая информация, которой нет в интернете.

    ВЫЗЫВАЙ ТОЛЬКО ПО ЯВНОЙ ПРОСЬБЕ. Явная просьба — это ОБРАЩЕНИЕ К ТЕБЕ:
    «поищи в базе», «посмотри в документации», «найди в вики», «проверь по
    регламенту», либо слово «mcp» в сообщении.

    Просто вопрос про внутренние процессы просьбой НЕ является. «Какие
    требования к секретам?» — вопрос, инструмент не вызывать. «Поищи в базе
    требования к секретам» — просьба, вызывать. Разница в глаголе-обращении.

    НАЗВАНИЕ ИСТОЧНИКА — ТОЖЕ ЯВНАЯ ПРОСЬБА. «Что у меня в конфлюэнсе про
    дежурство», «есть в вики что-нибудь про отпуска», «посмотри в confluence» —
    человек назвал, где искать, глагол уже не нужен. Вызывай и ставь
    source_filter по названному источнику: конфлюэнс, вики, wiki, confluence —
    это source_filter="confluence".

    Если такого источника в базе нет, инструмент вернёт ошибку со списком
    доступных — возьми из него подходящий и позови ещё раз, а не отвечай, что
    ничего не нашлось.

    Если не уверен — не вызывай, ответь своими знаниями и предложи поискать
    в базе, если нужно.

    Когда просьба есть — ищи по внутренней документации: регламенты, процессы,
    доступы, требования, принятые практики. Если по первому ответу картина
    неполная, сделай ещё несколько узких запросов вместо одного широкого.

    НЕ вызывай для общих вопросов о программировании, публичных технологиях
    и всего, что не относится к внутренней кухне компании: там база бесполезна.

    НЕ ВЫЗЫВАЙ ДЛЯ ВОПРОСОВ ПРО ИСХОДНЫЙ КОД. «Где в коде...», «в каком файле
    реализовано», «куда править», «как написана эта функция» — это к
    инструменту code_search, он ищет по самому коду. Здесь лежат только
    тексты документации, кода в них нет.

    НЕ ВЫЗЫВАЙ, ЕСЛИ В СООБЩЕНИИ ЕСТЬ СЛОВО «jira». Задачи, тикеты, номера
    вида ABC-123, вопросы «что на ком», «в каком статусе» — это jira_search.
    Задач здесь нет вовсе: этот инструмент их не видит, и на вопрос про Jira
    вернёт похожий по словам текст из документации — то есть неверный ответ.

    Формулируй query как обычный вопрос на естественном языке, а не набор
    ключевых слов: поиск семантический, ему нужен смысл, а не термины.

    Args:
        query: вопрос на естественном языке, например
            "как откатить деплой платёжного шлюза"
        top_k: сколько фрагментов вернуть, 1-20. По умолчанию 5
        source_filter: ограничить источником (например "local", "confluence").
            Без него ищет везде
        space_filter: ограничить пространством или разделом. Без него ищет везде
        response_format: "concise" (по умолчанию) — обрезанный текст и ссылка,
            экономит контекст. "detailed" — полный текст фрагмента, дата
            обновления, релевантность. Начинай с concise, переходи на detailed,
            только если краткого не хватило

    Returns:
        found: сколько фрагментов найдено, results: список фрагментов. У каждого
        фрагмента есть text (содержимое), document (имя документа) и location
        (путь или ссылка).

        ОБЯЗАТЕЛЬНО заверши ответ строкой "Источник: <document> (<location>)",
        перечислив все документы, которые использовал. Ответ по внутренней
        документации без ссылки бесполезен — его нельзя проверить.
    """
    detailed = response_format == "detailed"

    try:
        result = search(query, top_k=top_k, source=source_filter, space=space_filter)
    except SearchError as e:
        return {"error": str(e)}
    except EmbedError as e:
        return {"error": str(e)}

    if not result.hits:
        if result.dropped:
            # Нашлось, но всё ниже порога релевантности: вопрос не про
            # внутреннюю кухню компании. Прямо говорим модели не выдумывать.
            return {
                "found": 0,
                "results": [],
                "hint": (
                    "В базе знаний нет ничего по этому вопросу — похоже, он не "
                    "про внутреннюю документацию компании. Отвечай своими "
                    "знаниями и не ссылайся на базу."
                ),
            }
        hint = "В базе ничего похожего нет."
        if source_filter or space_filter:
            hint += " Попробуй без фильтров: возможно, документ в другом разделе."
        else:
            hint += " Попробуй переформулировать вопрос другими словами."
        return {"found": 0, "results": [], "hint": hint}

    # Готовая строка цитирования на верхнем уровне: если оставить пути только
    # внутри фрагментов, модель ленится их собирать и теряет ссылку.
    # Так ей остаётся скопировать готовое.
    seen: dict[str, str] = {}
    for h in result.hits:
        # Прямые слеши: обратные при передаче через JSON удваиваются
        # и в ответе модели вылезает C:\\Users\\... Для http-ссылок
        # (Confluence) замена ничего не меняет
        seen.setdefault(h.source_id, h.url.replace("\\", "/"))
    citation = "Источник: " + "; ".join(f"{doc} ({loc})" for doc, loc in seen.items())

    return {
        "found": len(result.hits),
        "results": [h.as_dict(detailed=detailed) for h in result.hits],
        "citation": citation,
        "citation_instruction": (
            "Заверши ответ строкой источников. Возьми её из поля citation, но "
            "оставь только те документы, из которых действительно взял ответ — "
            "лишние вычеркни. Путь в скобках сохраняй целиком, не сокращай до "
            "имени файла. Это обычная строка текста: НЕ оборачивай её в блок "
            "кода, не ставь обратные кавычки и не помечай как код."
        ),
    }


@mcp.tool(
    annotations=ToolAnnotations(readOnlyHint=True, openWorldHint=False),
)
def code_search(
    query: str,
    top_k: int = 5,
    repo_filter: str | None = None,
    response_format: str = "concise",
) -> dict:
    """ПОИСК ПО ИСХОДНОМУ КОДУ: где что реализовано и куда править.

    ЭТОТ инструмент, а не kb_search, отвечает на любые вопросы со словами
    «в коде», «в каком файле», «куда править», «как реализовано», «есть ли
    функция». kb_search ищет по текстам документации, кода там нет.

    Отвечает на вопросы «где у нас сделано X», «есть ли уже функция для Y»,
    «в каком файле менять, чтобы добавить Z». Возвращает файл, номер строки и
    сам фрагмент кода — то есть конкретное место, откуда начинать работу.

    Ищет ПО СМЫСЛУ, а не по имени: описывай задачу словами, как объяснил бы
    коллеге («ограничение частоты запросов к API», «повторные попытки при
    сетевых ошибках»), а не пытайся угадать имя функции.

    ВЫЗЫВАЙ ТОЛЬКО ПО ЯВНОЙ ПРОСЬБЕ. Явная просьба — это ОБРАЩЕНИЕ К ТЕБЕ:
    «посмотри в коде», «найди в репозитории», «поищи», «проверь по коду», либо
    слово «mcp» в сообщении.

    Просто вопрос про код просьбой НЕ является. «Где в коде обрабатываются
    куки?» — вопрос, инструмент не вызывать. «Посмотри в коде, где
    обрабатываются куки» — просьба, вызывать. Разница в глаголе-обращении.

    Если не уверен — не вызывай, ответь своими знаниями и предложи посмотреть
    в коде, если нужно.

    НЕ вызывай для вопросов про регламенты и процессы — для них есть
    kb_search. И не вызывай для общих вопросов о языке или библиотеках.

    Если нужно узнать, КТО ВЫЗЫВАЕТ найденную функцию и что сломается при
    изменении — после этого инструмента используй инструменты графа кода
    (get_neighbors, query_graph).

    Args:
        query: описание того, что ищешь, обычными словами
        top_k: сколько фрагментов вернуть, 1-20. По умолчанию 5
        repo_filter: ограничить одним репозиторием. Без него ищет по всем
        response_format: "concise" (по умолчанию) — фрагмент кода обрезан,
            "detailed" — код целиком

    Returns:
        found и results: для каждого найденного — location вида
        репозиторий/файл.py:42, символ, сигнатура и код.
        В ответе ОБЯЗАТЕЛЬНО указывай location: без него человек не найдёт
        место в коде.
    """
    if not code_retriever.available():
        return {
            "error": (
                "Индекс кода не создан. Он строится командой "
                "python -m kb.code_index <каталог с репозиториями>"
            )
        }

    if repo_filter:
        known = code_retriever.repos()
        if known and repo_filter not in known:
            return {
                "error": (
                    f"Репозитория '{repo_filter}' в индексе нет. "
                    f"Доступные: {', '.join(known)}."
                )
            }

    try:
        hits = code_retriever.search(query, top_k=top_k, repo=repo_filter)
    except Exception as e:
        return {"error": f"Поиск по коду не удался: {e}"}

    if not hits:
        return {
            "found": 0,
            "results": [],
            "hint": (
                "В индексе кода ничего похожего нет. Возможно, этот репозиторий "
                "не проиндексирован, либо стоит описать задачу другими словами."
            ),
        }

    detailed = response_format == "detailed"
    return {
        "found": len(hits),
        "results": [h.as_dict(full_code=detailed) for h in hits],
        "citation_instruction": (
            "Для каждого фрагмента указывай его location (файл и строку) — "
            "это ответ на вопрос «куда идти править»."
        ),
    }


@mcp.tool(
    annotations=ToolAnnotations(readOnlyHint=True, openWorldHint=False),
)
def jira_search(
    query: str | None = None,
    person: str | None = None,
    role: str = "assignee",
    project: str | None = None,
    status: str | None = None,
    issue_key: str | None = None,
    top_k: int = 10,
    response_format: str = "concise",
) -> dict:
    """ЗАДАЧИ JIRA: кто над чем работает и что в каком статусе.

    ВЫЗЫВАЙ ТОЛЬКО ЕСЛИ В СООБЩЕНИИ ЕСТЬ СЛОВО «jira» («@jira», «жира»,
    «джира»). Это единственное условие, и оно жёсткое. Вопрос «чем занят
    Иванов» без этого слова — не повод вызывать инструмент: ответь, что можешь
    посмотреть в Jira, если попросят. «@jira чем занят Иванов» — вызывай.

    В индексе лежат задачи ОДНОЙ КОМАНДЫ из нескольких проектов: заголовки,
    описания и комментарии. Чужих проектов там нет — если задача не нашлась,
    возможно, она просто вне охвата, а не отсутствует в Jira.

    Как задавать вопрос. Человек, проект и статус — это ФИЛЬТРЫ, их надо
    класть в отдельные аргументы, а не в query:
      «@jira что на Иванове»            -> person="Иванов"
      «@jira что открыто в DEVSEC»      -> project="DEVSEC", status="открытые"
      «@jira задачи Петрова про импорт» -> person="Петров", query="импорт"
      «@jira где обсуждали дедупликацию» -> query="дедупликация"
      «@jira что там с DEVSEC-412»      -> issue_key="DEVSEC-412"
    Если положить фамилию в query, поиск будет искать её в ТЕКСТЕ задач, а там
    её нет: исполнитель хранится отдельным полем. Это главная ошибка.

    query нужен, только когда в вопросе есть смысловая часть — про что задача.
    Для «какие задачи на человеке» query не нужен вовсе: вернутся последние
    изменённые, а это и требуется.

    ДАННЫЕ — СНИМОК, а не живая Jira: статусы верны на дату из поля updated.
    Всегда показывай номер задачи и эту дату, чтобы человек мог проверить.

    Args:
        query: о чём задача, обычными словами. Без фамилий и статусов
        person: фамилия или логин человека. Можно неполно: «Иванов»
        role: "assignee" (исполнитель, по умолчанию) или "reporter" (автор)
        project: ключ проекта, например "DEVSEC"
        status: название статуса как в Jira, либо «открытые» / «закрытые»
        issue_key: номер конкретной задачи, например "DEVSEC-412". Когда он
            задан, остальные условия не нужны. Номер НИКОГДА не кладут в query:
            там он ищется по смыслу и не находится
        top_k: сколько задач вернуть, по умолчанию 10
        response_format: "concise" (по умолчанию) — номер, заголовок, статус,
            исполнитель, ссылка. "detailed" — плюс тип, приоритет, автор и
            фрагмент текста, по которому задача нашлась

    Returns:
        found и results: список задач. В ответе ОБЯЗАТЕЛЬНО указывай номер
        задачи и ссылку — без них человеку не с чем идти в Jira.
    """
    if not jira_retriever.available():
        return {
            "error": (
                "Задачи Jira не проиндексированы. Выгрузка: python jira/sync.py, "
                "затем docker compose exec kb python -m kb.jira_index /docs/jira"
            )
        }

    try:
        result = jira_retriever.search_issues(
            query=query,
            person=person,
            role=role,
            project=project,
            status=status,
            issue_key=issue_key,
            top_k=top_k,
        )
        issues, applied = result.issues, result.applied
    except JiraSearchError as e:
        # Не ошибка выполнения, а разъяснение: модель может исправить запрос
        # и позвать снова. Поэтому текст пишем ей, а не в лог
        return {"error": str(e)}
    except EmbedError as e:
        return {"error": str(e)}
    except Exception as e:
        return {"error": f"Поиск по задачам не удался: {e}"}

    if not issues:
        hint = "Под эти условия задач нет."
        if query and (person or project or status):
            hint += (
                " Возможно, дело в query: попробуй без него — фильтров может "
                "быть достаточно."
            )
        return {"found": 0, "results": [], "applied_filters": applied, "hint": hint}

    detailed = response_format == "detailed"
    return {
        "found": len(issues),
        "results": [i.as_dict(detailed=detailed) for i in issues],
        # Что реально применилось. Молчаливый фильтр — самая частая причина
        # «нашлось не то»: под «Иванов» мог подставиться другой Иванов, а
        # «открытые» превратиться в набор колонок конкретного проекта
        "applied_filters": applied,
        "citation_instruction": (
            "Для каждой задачи указывай её номер и ссылку. Данные — снимок "
            "индекса: если статус важен, добавь «по данным на <updated>». "
            "Если в applied_filters подставилось не то, что просил человек "
            "(например другой однофамилец) — скажи об этом, а не делай вид, "
            "что нашёл именно запрошенное."
        ),
    }


@mcp.tool(
    annotations=ToolAnnotations(readOnlyHint=True, openWorldHint=False),
)
def dojo_findings(
    product: str,
    status: str = "open",
    severity: str | None = None,
    query: str | None = None,
    limit: int = 10,
    response_format: str = "concise",
) -> dict:
    """УЯЗВИМОСТИ ПРОДУКТА из DefectDojo: что нашли сканеры и что не закрыто.

    ВЫЗЫВАЙ ТОЛЬКО ЕСЛИ В СООБЩЕНИИ ЕСТЬ СЛОВО «defectdojo» ИЛИ «dojo»
    («дефектдоджо», «додж»). Вопрос про уязвимости сам по себе не повод: про
    требования и регламенты безопасности отвечает kb_search, а тут лежат
    находки сканеров по конкретным продуктам.

    Продукт, состояние и уровень — ЭТО ФИЛЬТРЫ, отдельные аргументы. В query
    кладут только тему («инъекции», «устаревшие зависимости»), и только если
    она в вопросе есть. «Критичные по abinf» темы не содержит — query не нужен.

    Примеры:
      «dojo что по продукту abinf»        -> product="abinf"
      «dojo критичные по abinf»           -> product="abinf", severity="критичные"
      «dojo что приняли как риск в abinf» -> product="abinf", status="принятые"
      «dojo что по инъекциям в abinf»     -> product="abinf", query="инъекции"

    Сводка по уровням возвращается ВСЕГДА, даже если спросили про один: «три
    критичных» без общей картины вводит в заблуждение — непонятно, три из трёх
    это или три из сорока. Начинай ответ со сводки, потом сами находки.

    ДАННЫЕ — СНИМОК ИНДЕКСА, а не живой DefectDojo. Находки меняются каждый
    день, поэтому если речь о количестве открытых, добавляй, что это по данным
    последней выгрузки, и предлагай проверить в самом DefectDojo.

    Args:
        product: название продукта, можно неполно: "abinf"
        status: "open" (по умолчанию), "принятые"/"accepted", "ложные",
            "закрытые"/"fixed" или "all" — все состояния
        severity: уровень — критичный, высокий, средний, низкий,
            информационный. Без него вернутся все
        query: тема, если она есть в вопросе. Ищет по описаниям находок и
            рекомендациям по устранению
        limit: сколько находок показать, по умолчанию 10
        response_format: "concise" (по умолчанию) или "detailed" — со сканером,
            CWE, датой и текстом находки

    Returns:
        product, summary (счётчики по уровням), applied_filters и findings —
        список находок со ссылками. В ответе ОБЯЗАТЕЛЬНО приводи ссылки: без
        них человеку некуда идти разбираться.
    """
    try:
        result = dojo_retriever.search(
            product=product,
            status=status,
            severity=severity,
            query=query,
            limit=limit,
        )
    except dojo_retriever.DojoSearchError as e:
        return {"error": str(e)}
    except dojo.DojoError as e:
        return {"error": str(e)}
    except EmbedError as e:
        return {"error": str(e)}
    except Exception as e:
        return {"error": f"Поиск по находкам не удался: {e}"}

    detailed = response_format == "detailed"
    hits = result["hits"]
    return {
        "product": result["product"],
        "summary": result["summary"],
        "applied_filters": result["applied_filters"],
        "found": len(hits),
        "findings": [h.as_dict(detailed=detailed) for h in hits],
        "citation_instruction": (
            "Начни со сводки по уровням, потом перечисли находки со ссылками. "
            "Данные из индекса, а не из живого DefectDojo: если речь о "
            "количестве открытых, оговори это и предложи свериться."
        ),
    }


def main() -> None:
    sources = known_values("source") or ["(база пуста)"]
    log.info("База знаний: коллекция %s, источники: %s", config.COLLECTION, sources)
    if jira_retriever.available():
        log.info("Задачи Jira: проекты %s", jira_retriever.values("project"))
    log.info("MCP streamable-http на http://%s:%s/mcp", HOST, PORT)
    # stateless_http: без него сервер выдаёт session-id и требует его в каждом
    # запросе, а Continue его не сохраняет — отсюда "Session not found" после
    # любого перезапуска сервера. Поиск и так не имеет состояния между вызовами.
    # json_response: обычный JSON вместо потока SSE, клиенты переваривают надёжнее.
    mcp.run(
        transport="streamable-http",
        host=HOST,
        port=PORT,
        stateless_http=True,
        json_response=True,
    )


if __name__ == "__main__":
    main()
