#!/bin/sh
# Обновление кода по расписанию: репозитории, граф и поиск по коду.
#
#   repos/cron.sh
#
# Строка для cron — раз в сутки ночью:
#
#   0 2 * * * /srv/local-ai/repos/cron.sh >> ~/logs/local-ai-code.log 2>&1
#
# Ставится вместе с остальными одной командой: ./install-cron.sh
# (или sudo ./install-timers.sh, если cron нет).
#
# Почему раз в сутки, а не раз в два часа, как Confluence и Jira: индексация
# кода пока не инкрементальная — каждый прогон пересчитывает эмбеддинги всего
# кода и надолго занимает эмбеддер, который делит видеокарту с чатом. Ночью
# это никому не мешает. Чаще — только после того, как индексация научится
# пропускать неизменившиеся файлы.
#
# Запускать от ТОГО ЖЕ пользователя, кому принадлежат клоны в CODE_DIR: от root
# новые клоны окажутся root-овыми, и удалить их без sudo будет нельзя.
# install-timers.sh об этом заботится сам.
#
# Два шага:
#   1. repos/sync.py — git: склонировать новые, обновить остальные (на хосте)
#   2. update-code.sh — граф (code-graph) и векторный индекс (kb) по CODE_DIR
# Второй шаг выполняется, даже если первый споткнулся на одном репозитории:
# остальные обновились, и индекс должен это увидеть. Код возврата при этом
# ненулевой, чтобы ошибка была заметна в логе и в статусе таймера.

set -u

# У cron урезанный PATH: без этого не найдутся ни docker, ни python3
PATH="/usr/local/bin:/usr/bin:/bin:${PATH:-}"
export PATH

cd "$(dirname "$0")/.."

# Замок свой у каждого пользователя: файл, созданный root, обычный
# пользователь открыть на запись не сможет — и прогон падал бы на замке
LOCK="${TMPDIR:-/tmp}/local-ai-code-$(id -u).lock"
if command -v flock >/dev/null 2>&1; then
    exec 9>"$LOCK"
    if ! flock -n 9; then
        echo "$(date '+%Y-%m-%d %H:%M:%S') прошлый прогон ещё идёт, пропускаю"
        exit 0
    fi
else
    # Без этой проверки отсутствие flock выглядело бы как «прошлый прогон
    # ещё идёт» — и обновление молча не выполнялось бы никогда
    echo "$(date '+%Y-%m-%d %H:%M:%S') [!] flock не найден (пакет util-linux) — иду без защиты от наложения"
fi

rc=0

echo "$(date '+%Y-%m-%d %H:%M:%S') репозитории"
python3 repos/sync.py || rc=1

echo "$(date '+%Y-%m-%d %H:%M:%S') граф и поиск по коду"
./update-code.sh || rc=1

if [ "$rc" = "0" ]; then
    echo "$(date '+%Y-%m-%d %H:%M:%S') готово"
else
    echo "$(date '+%Y-%m-%d %H:%M:%S') готово С ОШИБКАМИ — см. выше"
fi
exit "$rc"
